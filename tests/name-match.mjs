import fs from 'node:fs'; import vm from 'node:vm'; import assert from 'node:assert';
const src = fs.readFileSync(new URL('../Code.gs', import.meta.url), 'utf8');
const pick = n => { const i = src.indexOf(n); assert(i >= 0, n); return i; };
const start = pick('function normName'), end = src.indexOf('\n}', pick('function namesRelated')) + 2;
const ctx = {}; vm.createContext(ctx); vm.runInContext(src.slice(start, end) + '\nthis.namesRelated = namesRelated;', ctx);
const ok = [['簡晨光','晨光弟兄'],['簡晨光','簡弟兄'],['簡晨光','小光'],['王小明','小明'],['王小明','明哥'],['陳美玲','美玲姊妹'],['陳美玲','阿玲'],['林師母','林師母'],['Isaiah Chien','Isaiah'],['Isaiah Chien','isaiah弟兄'],['張雅婷','雅婷 (婷婷)']];
const no = [['簡晨光','王小明'],['陳美玲','李大華'],['Isaiah Chien','John'],['張雅婷','劉志強']];
for (const [a,b] of ok) assert.ok(ctx.namesRelated(a,b), `should match: ${a} / ${b}`);
for (const [a,b] of no) assert.ok(!ctx.namesRelated(a,b), `should NOT match: ${a} / ${b}`);
console.log(`name-match ${ok.length + no.length}/${ok.length + no.length} OK`);
